class NutritionInfo {
  const NutritionInfo({
    required this.calories,
    required this.carbs,
    required this.fat,
    required this.fiber,
    required this.protein,
  });

  /// kcal
  final double calories;

  /// grams
  final double carbs;

  /// grams
  final double fat;

  /// grams
  final double fiber;

  /// grams
  final double protein;
}
